"""Write the RTL constants package and fixed-point test vectors.

    python gen_vectors.py [--out ../vectors] [--pkg ../rtl/lockin_pkg.sv] [--seed 0] [--scale 1]

rtl/lockin_pkg.sv carries every width, constant, FIR coefficient and LUT entry
from params.py, so the RTL and the model cannot drift apart. Re-run this after
any change to params.py.

Vector files are plain text, one sample per line, space-separated decimal
integers, with '#' header lines naming the columns.
"""

import argparse
import math
from dataclasses import replace
from pathlib import Path

import numpy as np

from fixed_point import cordic_atan_table, sine_lut
from lockin_fixed import (LockinFixed, cic_decimate, codes_to_xd, coil_dac,
                          dac_out, decimate_chain, fir_coeffs, fir_decimate)
from params import OUT_SEL, LockinConfig, Regs
from sensor_model import SensorParams, detector_output

ROOT = Path(__file__).resolve().parent.parent


def write(path, cols, rows, note=""):
    with open(path, "w") as f:
        if note:
            f.write(f"# {note}\n")
        f.write("# " + " ".join(cols) + "\n")
        for r in rows:
            f.write(" ".join(str(int(v)) for v in r) + "\n")


def _array(f, decl, values, per_line=8):
    f.write(f"  localparam {decl} = '{{\n    ")
    f.write(",\n    ".join(", ".join(str(v) for v in values[i:i + per_line])
                           for i in range(0, len(values), per_line)))
    f.write("\n  };\n")


def write_pkg(path, cfg: LockinConfig, regs: Regs):
    ints = {k: getattr(cfg, k) for k in vars(cfg) if isinstance(getattr(cfg, k), int)
            and not isinstance(getattr(cfg, k), bool)}
    ints.update(CIC_WIDTH=cfg.cic_width, CIC_SHIFT=cfg.cic_shift, R_TOTAL=cfg.r_total,
                IQ_FRAC_BITS=cfg.iq_frac_bits)
    with open(path, "w") as f:
        f.write("// Generated by model/gen_vectors.py from model/params.py. Do not edit.\n")
        f.write(f"// fs_adc={cfg.fs_adc:g} Hz  f_mod={cfg.f_mod_actual:.6f} Hz  "
                f"fs_dec={cfg.fs_dec:g} Hz  fs_loop={cfg.fs_loop:g} Hz\n")
        if cfg.sim_scale != 1:
            f.write(f"// WARNING: SIM_SCALE={cfg.sim_scale}; simulation only, not for synthesis\n")
        f.write("package lockin_pkg;\n\n")
        for k, v in ints.items():
            f.write(f"  localparam int {k.upper()} = {v};\n")
        f.write(f"  localparam logic [{cfg.nco_bits - 1}:0] NCO_INC = {cfg.nco_bits}'d{cfg.nco_inc};"
                "   // per fabric clock\n")
        f.write(f"  localparam logic [{cfg.nco_bits - 1}:0] NCO_STEP = {cfg.nco_bits}'d{cfg.nco_step};"
                "  // per decimated sample\n")
        f.write("  // DAC2 source select\n")
        for i, name in enumerate(OUT_SEL):
            f.write(f"  localparam int SEL_{name.upper()} = {i};\n")
        f.write("  // Register reset values\n")
        for k, v in vars(regs).items():
            v = int(v)
            lit = f"64'sd{v}" if v >= 0 else f"-64'sd{-v}"
            f.write(f"  localparam longint REG_{k.upper()}_RST = {lit};\n")

        h = fir_coeffs(cfg.fir_taps, cfg.fir_r, cfg.cic_order, cfg.fir_coef_bits)
        _array(f, f"logic signed [{cfg.fir_coef_bits - 1}:0] FIR_COEF [{len(h)}]", h)
        lut = sine_lut(cfg.lut_addr_bits, cfg.lut_bits)
        _array(f, f"logic signed [{cfg.lut_bits - 1}:0] SINE_LUT [{len(lut)}]", lut, 16)
        atan = cordic_atan_table(cfg.cordic_iters, cfg.phase_bits + cfg.cordic_guard)
        f.write("  // CORDIC_ATAN units: full turn = 2^(PHASE_BITS + CORDIC_GUARD)\n")
        _array(f, f"int CORDIC_ATAN [{len(atan)}]", atan)
        kinv = round(2 ** 16 / math.prod(math.sqrt(1 + 2.0 ** (-2 * i))
                                         for i in range(cfg.cordic_iters)))
        f.write(f"  localparam int CORDIC_KINV = {kinv};  // Q0.16\n")
        f.write("\nendpackage\n")


def lockin_vectors(out, cfg, sp, regs, n):
    """x_d in, DC/I/Q out after every sample (lockin_core.sv)."""
    core = LockinFixed(cfg, regs)
    t = np.arange(n) / cfg.fs_dec
    _, codes = detector_output(t, 0.15 * np.sin(2 * np.pi * 3.0 * t), sp)
    xd = codes_to_xd(codes, cfg)
    rows = []
    for x in xd:
        core.process([x])
        rows.append((core.dc, core.I1, core.Q1, core.X2, core.Y2))
    write(out / "lockin_in.txt", ["xd"], xd[:, None])
    write(out / "lockin_out.txt", ["dc", "I1", "Q1", "X2", "Y2"], rows)
    write(out / "lockin_regs.txt", ["nco_step", "phase_off1", "phase_off2"],
          [(cfg.nco_step, regs.phase_off1, regs.phase_off2)])


def top_vectors(out, cfg, sp, regs, n_dec):
    """ADC codes in at fs_adc; DC/I/Q and DAC2 after every decimated sample (lockin_top.sv)."""
    t = np.arange(n_dec * cfg.r_total) / cfg.fs_adc
    _, codes = detector_output(t, 0.1, sp)
    core = LockinFixed(cfg, regs)
    vals = {}
    rows = []
    for x in decimate_chain(codes, cfg):
        core.process([x])
        vals = dict(I1=core.I1, Q1=core.Q1, X2=core.X2, Y2=core.Y2, dc=core.dc, xd=core.xd)
        dac2 = dac_out(vals[OUT_SEL[regs.out_sel]], regs.out_gain, regs.out_shift,
                       regs.out_offset, cfg)
        rows.append((core.dc, core.I1, core.Q1, core.X2, core.Y2, dac2))
    write(out / "top_adc.txt", ["adc"], codes[:, None], f"fs {cfg.fs_adc:g}")
    write(out / "top_out.txt", ["dc", "I1", "Q1", "X2", "Y2", "dac2"], rows)
    write(out / "top_regs.txt",
          ["nco_inc", "phase_off1", "phase_off2", "coil_amp", "out_sel", "out_gain", "out_shift",
           "out_offset"],
          [(cfg.nco_inc, regs.phase_off1, regs.phase_off2, regs.coil_amp, regs.out_sel,
            regs.out_gain, regs.out_shift, regs.out_offset)])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "vectors"))
    ap.add_argument("--pkg", default=str(ROOT / "rtl" / "lockin_pkg.sv"))
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--scale", type=int, default=1, help="sim time scale (1 = real)")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    cfg = LockinConfig() if args.scale == 1 else LockinConfig().scaled(args.scale)
    rng = np.random.default_rng(args.seed)
    Path(args.pkg).parent.mkdir(parents=True, exist_ok=True)
    write_pkg(args.pkg, cfg, Regs())
    sp = SensorParams(f_mod=cfg.f_mod_actual, noise_sigma=0.002, seed=args.seed)
    off1 = 0x0C000000
    off2 = (2 * off1 - (1 << 30)) % (1 << 32)

    # CIC + FIR: full-rate burst
    t = np.arange(cfg.r_total * 64) / cfg.fs_adc
    _, codes = detector_output(t, 0.2, sp)
    cic = cic_decimate(codes, cfg)
    write(out / "cic_in.txt", ["adc"], codes[:, None], f"seed {args.seed}, fs {cfg.fs_adc:g}")
    write(out / "cic_out.txt", ["cic"], cic[:, None])
    write(out / "fir_out.txt", ["fir"], fir_decimate(cic, cfg)[:, None])

    # Lock-in core at the decimated rate: 0.5 s
    lockin_vectors(out, cfg, sp, Regs(phase_off1=off1, phase_off2=off2), int(0.5 * cfg.fs_dec))

    # DAC2 output stage: random sources, gains, shifts, offsets
    n = 3000
    lim = 1 << (cfg.mix_bits - 1)
    src = rng.integers(-lim, lim, size=(n, 6))
    src[:, 4:] >>= cfg.mix_bits - cfg.data_bits          # dc, xd are data_bits wide
    sel = rng.integers(0, len(OUT_SEL), n)
    gain = rng.integers(0, 1 << cfg.out_gain_bits, n)
    shift = rng.integers(0, 32, n)
    offset = rng.integers(-(1 << (cfg.dac_bits - 1)), 1 << (cfg.dac_bits - 1), n)
    rows = [(*src[i], sel[i], gain[i], shift[i], offset[i],
             dac_out(int(src[i, sel[i]]), int(gain[i]), int(shift[i]), int(offset[i]), cfg))
            for i in range(n)]
    write(out / "dac_out.txt", [*OUT_SEL, "sel", "gain", "shift", "offset", "dac"], rows)

    # Coil NCO: run at 1 MHz so 50k clocks sweep the whole LUT many times
    coil_amp = 50000
    cfg_fast = replace(cfg, f_mod=1e6)
    write(out / "coil.txt", ["dac1"], coil_dac(np.arange(50_000), cfg_fast, coil_amp)[:, None])
    write(out / "coil_regs.txt", ["nco_inc", "coil_amp"], [(cfg_fast.nco_inc, coil_amp)])

    # Top: ADC -> CIC -> FIR -> core -> DAC2, 96 decimated samples
    top_regs = Regs(phase_off1=off1, phase_off2=off2, coil_amp=coil_amp,
                    out_sel=OUT_SEL.index("I1"), out_gain=3, out_shift=1, out_offset=-100)
    top_vectors(out, cfg, sp, top_regs, 96)

    print(f"wrote {args.pkg} and vectors to {out}")


if __name__ == "__main__":
    main()
